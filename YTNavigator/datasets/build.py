#!/usr/bin/env python3
"""Build the synthetic YT-Navigator benchmark dataset in Postgres.

Loads the fully synthetic "NeuralBytes" channel (channel_data.json) into the
exact tables both agent implementations query: app_channel / app_video /
app_videochunk plus the PGVector tables (langchain_pg_collection /
langchain_pg_embedding). Chunk embeddings are computed with the same model
the original app uses (BAAI/bge-small-en-v1.5), so retrieval behaves the same
as with scraped data - but the dataset is deterministic, self-contained, and
needs no YouTube access.

Tables are created if missing (schemas compatible with the Django app and
langchain_postgres; a later `manage.py migrate --fake-initial` accepts them).
Idempotent: if the channel is already loaded it does nothing unless --replace.

Usage:
    POSTGRES_HOST=... POSTGRES_USER=... python build.py [--replace]
    python build.py --fake-embeddings      # pipeline smoke without torch

Requires psycopg2-binary; sentence-transformers unless --fake-embeddings.
"""

import argparse
import json
import os
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "byLLM"))
from retrieval import fake_embedding  # noqa: E402  (shared with query-side fake mode)

DATA_FILE = Path(__file__).resolve().parent / "channel_data.json"
EMBEDDING_MODEL = os.environ.get("EMBEDDING_MODEL", "BAAI/bge-small-en-v1.5")

DDL = """
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS app_channel (
    id varchar(100) PRIMARY KEY,
    name varchar(100) NOT NULL,
    profile_image_url varchar(200) NOT NULL,
    description text NOT NULL,
    username varchar(100) NOT NULL,
    url varchar(200) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_video (
    id varchar(100) PRIMARY KEY,
    title varchar(100) NOT NULL,
    thumbnail varchar(200) NOT NULL,
    published_at timestamptz NOT NULL,
    channel_id varchar(100) NOT NULL REFERENCES app_channel (id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS app_videochunk (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start time NULL,
    "end" time NULL,
    text text NOT NULL,
    video_id varchar(100) NOT NULL REFERENCES app_video (id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS langchain_pg_collection (
    uuid uuid PRIMARY KEY,
    name varchar NOT NULL UNIQUE,
    cmetadata json
);

CREATE TABLE IF NOT EXISTS langchain_pg_embedding (
    id varchar PRIMARY KEY,
    collection_id uuid REFERENCES langchain_pg_collection (uuid) ON DELETE CASCADE,
    embedding vector,
    document varchar,
    cmetadata jsonb
);
"""


def connect():
    import psycopg2

    return psycopg2.connect(
        host=os.environ.get("POSTGRES_HOST", "localhost"),
        port=os.environ.get("POSTGRES_PORT", "5432"),
        user=os.environ.get("POSTGRES_USER", "postgres"),
        password=os.environ.get("POSTGRES_PASSWORD", ""),
        dbname=os.environ.get("POSTGRES_DB", "postgres"),
    )


def seconds_to_time(seconds):
    hours, remainder = divmod(int(seconds), 3600)
    minutes, secs = divmod(remainder, 60)
    return f"{hours:02d}:{minutes:02d}:{secs:02d}"


def real_embeddings(texts):
    try:
        from sentence_transformers import SentenceTransformer
    except ImportError:
        sys.exit(
            "sentence-transformers is required to build real embeddings "
            "(pip install sentence-transformers), or pass --fake-embeddings "
            "for a pipeline smoke test."
        )
    print(f"  embedding {len(texts)} chunks with {EMBEDDING_MODEL} ...")
    model = SentenceTransformer(EMBEDDING_MODEL)
    return [vector.tolist() for vector in model.encode(texts, batch_size=32, show_progress_bar=False)]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", default=str(DATA_FILE), help="Channel content JSON (default: channel_data.json)")
    parser.add_argument("--replace", action="store_true", help="Delete and rebuild the channel if already loaded")
    parser.add_argument(
        "--fake-embeddings",
        action="store_true",
        help="Deterministic pseudo-embeddings (no torch needed). Retrieval quality is meaningless - smoke tests only.",
    )
    args = parser.parse_args()

    data = json.loads(Path(args.data).read_text())
    channel = data["channel"]
    videos = data["videos"]
    collection_uuid = str(uuid.uuid5(uuid.NAMESPACE_URL, channel["id"]))

    conn = connect()
    conn.autocommit = False
    cur = conn.cursor()
    cur.execute(DDL)

    cur.execute("SELECT 1 FROM app_channel WHERE id = %s", (channel["id"],))
    if cur.fetchone():
        if not args.replace:
            conn.rollback()
            print(f"Channel '{channel['id']}' already loaded - nothing to do (use --replace to rebuild).")
            return
        print(f"Replacing existing channel '{channel['id']}' ...")
        cur.execute("DELETE FROM langchain_pg_collection WHERE name = %s", (channel["id"],))  # cascades to embeddings
        cur.execute(
            "DELETE FROM app_videochunk WHERE video_id IN (SELECT id FROM app_video WHERE channel_id = %s)",
            (channel["id"],),
        )
        if _table_exists(cur, "app_user"):
            cur.execute("UPDATE app_user SET channel_id = NULL WHERE channel_id = %s", (channel["id"],))
        cur.execute("DELETE FROM app_video WHERE channel_id = %s", (channel["id"],))
        cur.execute("DELETE FROM app_channel WHERE id = %s", (channel["id"],))

    # created_at/updated_at explicitly: Django's auto_now columns are NOT NULL
    # with no database-level default.
    cur.execute(
        "INSERT INTO app_channel (id, name, profile_image_url, description, username, url, created_at, updated_at) "
        "VALUES (%s, %s, %s, %s, %s, %s, now(), now())",
        (channel["id"], channel["name"], channel["profile_image_url"], channel["description"],
         channel["username"], channel["url"]),
    )

    all_texts, all_meta = [], []
    for video in videos:
        thumbnail = f"https://i.ytimg.com/vi/{video['id']}/hqdefault.jpg"
        cur.execute(
            "INSERT INTO app_video (id, title, thumbnail, published_at, channel_id) VALUES (%s, %s, %s, %s, %s)",
            (video["id"], video["title"], thumbnail, video["published_at"], channel["id"]),
        )
        for i, chunk in enumerate(video["chunks"]):
            start, duration = chunk["start"], chunk["duration"]
            cur.execute(
                'INSERT INTO app_videochunk (start, "end", text, video_id) VALUES (%s, %s, %s, %s)',
                (seconds_to_time(start), seconds_to_time(start + duration), chunk["text"], video["id"]),
            )
            all_texts.append(chunk["text"])
            all_meta.append(
                {
                    "id": f"{video['id']}:{i:03d}",
                    "video_id": video["id"],
                    "start_time": start,
                    "duration": duration,
                    "channel_id": channel["id"],
                    "text": chunk["text"],
                }
            )

    if args.fake_embeddings:
        print("  WARNING: --fake-embeddings - retrieval quality will be meaningless")
        vectors = [fake_embedding(t) for t in all_texts]
    else:
        vectors = real_embeddings(all_texts)

    cur.execute(
        "INSERT INTO langchain_pg_collection (uuid, name, cmetadata) VALUES (%s, %s, %s) ON CONFLICT DO NOTHING",
        (collection_uuid, channel["id"], json.dumps({})),
    )
    # Clear any embeddings left from a partially-completed earlier build (the
    # relational tables and the vector tables can get out of sync when a run
    # is interrupted or the schema is rebuilt under Django).
    cur.execute("DELETE FROM langchain_pg_embedding WHERE collection_id = %s", (collection_uuid,))
    for meta, vector in zip(all_meta, vectors):
        cur.execute(
            "INSERT INTO langchain_pg_embedding (id, collection_id, embedding, document, cmetadata) "
            "VALUES (%s, %s, %s::vector, %s, %s)",
            (meta["id"], collection_uuid, "[" + ",".join(f"{x:.8f}" for x in vector) + "]",
             meta["text"], json.dumps({k: v for k, v in meta.items() if k != "id"})),
        )

    conn.commit()

    cur.execute("SELECT COUNT(*) FROM app_video WHERE channel_id = %s", (channel["id"],))
    n_videos = cur.fetchone()[0]
    cur.execute(
        "SELECT COUNT(*) FROM langchain_pg_embedding e JOIN langchain_pg_collection c ON e.collection_id = c.uuid "
        "WHERE c.name = %s",
        (channel["id"],),
    )
    n_embeddings = cur.fetchone()[0]
    conn.close()
    print(
        f"Dataset ready: channel '{channel['name']}' ({channel['id']}), "
        f"{n_videos} videos, {len(all_texts)} chunks, {n_embeddings} embeddings "
        f"({'FAKE' if args.fake_embeddings else EMBEDDING_MODEL})."
    )


def _table_exists(cur, table):
    cur.execute("SELECT to_regclass(%s)", (table,))
    return cur.fetchone()[0] is not None


if __name__ == "__main__":
    main()
